export type UIKey = keyof (typeof ui)['en'];

export function useTranslations(lang: Lang) {
  return (key: UIKey) => ui[lang][key] ?? ui[defaultLang][key];
}

export function route(lang: Lang, key: RouteKey) {
  return routes[key][lang];
}

/** URL of a root-level product page for a given locale + slug. */
export function productUrl(lang: Lang, slug: string) {
  return lang === defaultLang ? `/${slug}/` : `/${lang}/${slug}/`;
}

export function blogUrl(lang: Lang, slug: string) {
  return `${routes.blog[lang]}${slug}/`;
}

export function dateLocale(lang: Lang) {
  return { en: 'en-GB', it: 'it-IT', sq: 'sq-AL' }[lang];
}
